const CUSTOM_FONTS_STORAGE_KEY = 'stylegram_custom_fonts_v1';

export function resolveFontFamily(fontId, customFonts = []) {
  const custom = customFonts.find(f => f.id === fontId);
  if (custom) return custom.family;
  const found = FONT_LIBRARY.find(f => f.id === fontId);
  return found ? found.family : 'Vazirmatn';
}

function arrayBufferToBase64(buffer) {
  const bytes = new Uint8Array(buffer);
  let binary = '';
  const chunk = 0x8000;
  for (let i = 0; i < bytes.length; i += chunk) {
    binary += String.fromCharCode(...bytes.subarray(i, i + chunk));
  }
  return btoa(binary);
}

function base64ToArrayBuffer(b64) {
  const binary = atob(b64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) {
    bytes[i] = binary.charCodeAt(i);
  }
  return bytes.buffer;
}

export async function loadCustomFontFile(file) {
  const baseName = file.name.replace(/\.(ttf|otf|woff2|woff)$/i, '').trim() || 'CustomFont';
  const safeFamily = 'Custom_' + baseName.replace(/[^a-zA-Z0-9_-]/g, '_') + '_' + Date.now();
  const buffer = await file.arrayBuffer();
  const face = new FontFace(safeFamily, buffer);
  await face.load();
  document.fonts.add(face);

  const fontObj = {
    id: safeFamily,
    name: `${baseName} (واردشده)`,
    lang: 'fa',
    cat: 'custom',
    family: safeFamily,
    status: 'فونت کاربر',
    fallback: false,
    sample: 'نمونه فونت اختصاصی StyleGram'
  };

  try {
    const existing = JSON.parse(localStorage.getItem(CUSTOM_FONTS_STORAGE_KEY) || '[]');
    existing.unshift({ ...fontObj, dataB64: arrayBufferToBase64(buffer) });
    localStorage.setItem(CUSTOM_FONTS_STORAGE_KEY, JSON.stringify(existing.slice(0, 8)));
  } catch {
    // Ignore quota errors for very large font files
  }

  return fontObj;
}

export async function loadStoredCustomFonts() {
  try {
    const stored = JSON.parse(localStorage.getItem(CUSTOM_FONTS_STORAGE_KEY) || '[]');
    const loaded = [];
    for (const item of stored) {
      if (!item.dataB64 || !item.family) continue;
      const buf = base64ToArrayBuffer(item.dataB64);
      const face = new FontFace(item.family, buf);
      await face.load();
      document.fonts.add(face);
      const { dataB64, ...meta } = item;
      loaded.push(meta);
    }
    return loaded;
  } catch {
    return [];
  }
}

export function deleteStoredCustomFont(fontId) {
  try {
    const stored = JSON.parse(localStorage.getItem(CUSTOM_FONTS_STORAGE_KEY) || '[]');
    const next = stored.filter(item => item.id !== fontId);
    localStorage.setItem(CUSTOM_FONTS_STORAGE_KEY, JSON.stringify(next));
  } catch {
    // Ignore storage errors
  }
}
